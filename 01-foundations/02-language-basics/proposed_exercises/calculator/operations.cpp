// Lets write the implementation of the basic arithmetic operations.

// 1º - Addition
float add(float a, float b){
    return a + b;
}

// 2º - Subtraction
float subtract(float a, float b){
    return a - b;
}

// 3º - Multiplication
float multiply(float a, float b){
    return a * b;
}

// 4º - Division
float divide(float a, float b){
    return a / b;
}